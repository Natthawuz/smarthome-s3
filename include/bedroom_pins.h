#define DHT22_PIN     38  // สาย Data ของ DHT22 (โมดูลนี้มัก pull-up ในตัวอยู่แล้ว) — ย้ายจาก IO1 หลังถอด SD
#define OLED_SDA_PIN  21  // OLED 1.3" (SH1106) I2C SDA — แชร์บัสกับ MPU-6050 (ไม่ใช่ IO42 เดิมแล้ว)
#define OLED_SCL_PIN  47  // OLED 1.3" I2C SCL — แชร์บัสกับ MPU-6050 (ไม่ใช่ IO41 เดิมแล้ว)
